//! With feature `gpu`:
//! * generates `race_state.glsl` (GLSL accessors) and `layout_gen.rs` (plane constants) in OUT_DIR from
//!   src/gpu/layout_spec.rs;
//! * compiles `shaders/*.comp` to SPIR-V in OUT_DIR with glslangValidator (from `GLSLANG_VALIDATOR`, the Vulkan SDK's
//!   `VULKAN_SDK`, or PATH). Without a compiler it falls back to the checked-in `shaders/prebuilt/`.
//!   `UMA_UPDATE_PREBUILT=1` copies the freshly compiled SPIR-V into `shaders/prebuilt/`.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

#[allow(dead_code)]
mod spec {
    include!("src/gpu/layout_spec.rs");
}
#[allow(dead_code)]
mod skill_spec {
    include!("src/gpu/skill_spec.rs");
}
use spec::{
    BTS_SECTIONS, FIELDS, Kind, MAX_BEHIND_NEAR_PARAMS, MAX_HORSES, MAX_MODIFIERS, MAX_ONE_TIME_MODIFIERS, ORDER_IN_OUT_TYPES,
    PK_STRATEGIES, RNG_WORDS, Scope,
};

fn words(k: Kind) -> u32 {
    if k == Kind::F64 { 2 } else { 1 }
}

/// First plane of each field (first word of the params buffer for params), the plane count and the param word
/// count.
fn bases() -> (Vec<u32>, u32, u32) {
    let (mut p, mut q) = (0, 0);
    let mut out = Vec::new();
    for f in FIELDS {
        let n = f.len * words(f.kind);
        match f.scope {
            Scope::Param => {
                out.push(q);
                q += n;
            }
            Scope::Horse => {
                out.push(p);
                p += n * MAX_HORSES;
            }
            Scope::Race => {
                out.push(p);
                p += n;
            }
        }
    }
    (out, p, q)
}

fn gen_glsl() -> String {
    let (bases, planes, param_words) = bases();
    let mut g = String::new();
    g += "// Generated by build.rs from src/gpu/layout_spec.rs: do not edit.\n";
    g += "#ifndef UMA_RACE_STATE_GLSL\n#define UMA_RACE_STATE_GLSL\n\n";
    g += "#ifndef STATE_BINDING\n#error \"define STATE_BINDING before including race_state.glsl\"\n#endif\n\n";
    g += &format!("const uint MAX_HORSES = {MAX_HORSES}u;\nconst uint STATE_PLANES = {planes}u;\n");
    for (name, v) in [
        ("MAX_BEHIND_NEAR_PARAMS", MAX_BEHIND_NEAR_PARAMS),
        ("MAX_MODIFIERS", MAX_MODIFIERS),
        ("MAX_ONE_TIME_MODIFIERS", MAX_ONE_TIME_MODIFIERS),
        ("RNG_WORDS", RNG_WORDS),
        ("BTS_SECTIONS", BTS_SECTIONS),
        ("PK_STRATEGIES", PK_STRATEGIES),
        ("ORDER_IN_OUT_TYPES", ORDER_IN_OUT_TYPES),
    ] {
        g += &format!("const uint {name} = {v}u;\n");
    }
    g += "\n";
    g += "layout(std430, binding = STATE_BINDING) buffer RaceState { uint st[]; };\n";
    g += "// Set in main(): the lane count of the dispatch and this invocation's lane.\nuint st_lanes;\nuint st_lane;\n";
    g += "uint st_get(uint plane) { return st[plane * st_lanes + st_lane]; }\n";
    g += "void st_set(uint plane, uint v) { st[plane * st_lanes + st_lane] = v; }\n\n";
    g += &format!("const uint PARAM_WORDS = {param_words}u;\n");
    g += "#ifndef PARAMS_BINDING\n#define PARAMS_BINDING 1\n#endif\n";
    g += "layout(std430, binding = PARAMS_BINDING) readonly buffer Params { uint prm[]; };\n\n";
    for (f, &base) in FIELDS.iter().zip(&bases) {
        let w = words(f.kind);
        if f.scope == Scope::Param {
            let (ty, load) = match f.kind {
                Kind::F32 => ("float", "uintBitsToFloat(prm[P])"),
                Kind::I32 => ("int", "int(prm[P])"),
                Kind::U32 => ("uint", "prm[P]"),
                Kind::Bool => ("bool", "(prm[P] != 0u)"),
                Kind::F64 => ("double", "packDouble2x32(uvec2(prm[P], prm[P + 1u]))"),
            };
            let (params, idx) = if f.len > 1 { ("uint k", format!("({base}u + k * {w}u)")) } else { ("", format!("{base}u")) };
            g += &format!("{ty} p_{}({params}) {{ return {}; }}\n", f.name, load.replace("P", &idx));
            continue;
        }
        let (ty, load, store) = match f.kind {
            Kind::F32 => ("float", "uintBitsToFloat(st_get(P))", "st_set(P, floatBitsToUint(v))"),
            Kind::I32 => ("int", "int(st_get(P))", "st_set(P, uint(v))"),
            Kind::U32 => ("uint", "st_get(P)", "st_set(P, v)"),
            Kind::Bool => ("bool", "(st_get(P) != 0u)", "st_set(P, v ? 1u : 0u)"),
            Kind::F64 => (
                "double",
                "packDouble2x32(uvec2(st_get(P), st_get(P + 1u)))",
                "uvec2 u = unpackDouble2x32(v); st_set(P, u.x); st_set(P + 1u, u.y)",
            ),
        };
        let (prefix, params, plane) = match (f.scope, f.len > 1) {
            (Scope::Horse, false) => ("h_", "uint h", format!("({base}u + h * {w}u)")),
            (Scope::Horse, true) => ("h_", "uint h, uint k", format!("({base}u + (k * MAX_HORSES + h) * {w}u)")),
            (Scope::Race, false) => ("r_", "", format!("{base}u")),
            (Scope::Race, true) => ("r_", "uint k", format!("({base}u + k * {w}u)")),
            (Scope::Param, _) => unreachable!(),
        };
        let sep = if params.is_empty() { "" } else { ", " };
        g += &format!("{ty} {prefix}{}({params}) {{ return {}; }}\n", f.name, load.replace("P", &plane));
        g += &format!("void set_{prefix}{}({params}{sep}{ty} v) {{ {}; }}\n", f.name, store.replace("P", &plane));
    }
    g += "\n#endif\n";
    g
}

fn gen_rust() -> String {
    let (bases, planes, param_words) = bases();
    let mut r = String::new();
    r += "// Generated by build.rs from src/gpu/layout_spec.rs: do not edit.\n";
    r += &format!("pub const STATE_PLANES: u32 = {planes};\npub const PARAM_WORDS: u32 = {param_words};\n");
    let mut all = Vec::new();
    for (i, (f, &base)) in FIELDS.iter().zip(&bases).enumerate() {
        let prefix = match f.scope {
            Scope::Horse => "H",
            Scope::Race => "R",
            Scope::Param => "P",
        };
        let c = format!("{prefix}_{}", f.name.to_uppercase());
        r += &format!(
            "pub const {c}: Field = Field {{ index: {i}, base: {base}, kind: Kind::{:?}, scope: Scope::{:?}, len: {}, name: {:?} }};\n",
            f.kind, f.scope, f.len, f.name
        );
        all.push(c);
    }
    r += &format!("pub const ALL_FIELDS: &[Field] = &[{}];\n", all.join(", "));
    r
}

/// `skill_layout.glsl` / `skill_gen.rs`: the trigger kind codes and the skill record offsets.
fn gen_skill(glsl: bool) -> String {
    let mut g = String::from("// Generated by build.rs from src/gpu/skill_spec.rs.\n\n");
    let mut c = |name: String, v: usize| {
        if glsl {
            g += &format!("const uint {name} = {v}u;\n");
        } else {
            g += &format!("pub const {name}: u32 = {v};\n");
        }
    };
    for (k, name) in skill_spec::KINDS.iter().enumerate() {
        c(format!("K_{name}"), k);
    }
    for (prefix, fields) in skill_spec::RECORDS {
        for (k, f) in fields.iter().enumerate() {
            c(format!("{prefix}_{}", f.to_uppercase()), k);
        }
        c(format!("{prefix}_WORDS"), fields.len());
    }
    c("MAX_RUNS".into(), skill_spec::MAX_RUNS as usize);
    g
}

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    if env::var_os("CARGO_FEATURE_GPU").is_none() {
        return;
    }
    println!("cargo:rerun-if-changed=shaders");
    println!("cargo:rerun-if-env-changed=GLSLANG_VALIDATOR");
    println!("cargo:rerun-if-env-changed=VULKAN_SDK");
    println!("cargo:rerun-if-changed=src/gpu/layout_spec.rs");
    println!("cargo:rerun-if-changed=src/gpu/skill_spec.rs");
    println!("cargo:rerun-if-env-changed=UMA_UPDATE_PREBUILT");
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    fs::write(out.join("race_state.glsl"), gen_glsl()).unwrap();
    fs::write(out.join("layout_gen.rs"), gen_rust()).unwrap();
    fs::write(out.join("skill_layout.glsl"), gen_skill(true)).unwrap();
    fs::write(out.join("skill_gen.rs"), gen_skill(false)).unwrap();
    let update_prebuilt = env::var_os("UMA_UPDATE_PREBUILT").is_some_and(|v| v == "1");
    let compiler = find_glslang();
    let mut sources: Vec<PathBuf> = fs::read_dir("shaders")
        .expect("shaders/")
        .map(|e| e.unwrap().path())
        .filter(|p| p.extension().is_some_and(|x| x == "comp"))
        .collect();
    sources.sort();
    for src in &sources {
        let name = src.file_stem().unwrap().to_str().unwrap();
        let dst = out.join(format!("{name}.spv"));
        match &compiler {
            Some(glslang) => {
                let o = Command::new(glslang)
                    .args(["-V", "--target-env", "vulkan1.2", "-Ishaders/lib"])
                    .arg(format!("-I{}", out.display()))
                    .arg("-o")
                    .arg(&dst)
                    .arg(src)
                    .output()
                    .unwrap_or_else(|e| panic!("running {}: {e}", glslang.display()));
                if !o.status.success() {
                    panic!(
                        "glslangValidator failed on {}:\n{}{}",
                        src.display(),
                        String::from_utf8_lossy(&o.stdout),
                        String::from_utf8_lossy(&o.stderr)
                    );
                }
                if update_prebuilt {
                    fs::create_dir_all("shaders/prebuilt").unwrap();
                    fs::copy(&dst, Path::new("shaders/prebuilt").join(format!("{name}.spv"))).unwrap();
                }
            }
            None => {
                let pre = Path::new("shaders/prebuilt").join(format!("{name}.spv"));
                fs::copy(&pre, &dst).unwrap_or_else(|e| panic!("no glslangValidator and no {}: {e}", pre.display()));
            }
        }
    }
    if compiler.is_none() {
        println!(
            "cargo:warning=glslangValidator not found (install the Vulkan SDK or set GLSLANG_VALIDATOR): using \
             shaders/prebuilt/*.spv, which only match the GLSL sources as of their last regeneration"
        );
    }
}

fn find_glslang() -> Option<PathBuf> {
    if let Some(p) = env::var_os("GLSLANG_VALIDATOR") {
        return Some(PathBuf::from(p));
    }
    let exe = if cfg!(windows) { "glslangValidator.exe" } else { "glslangValidator" };
    if let Some(sdk) = env::var_os("VULKAN_SDK") {
        for sub in ["Bin", "bin"] {
            let p = Path::new(&sdk).join(sub).join(exe);
            if p.exists() {
                return Some(p);
            }
        }
    }
    env::var_os("PATH").and_then(|paths| env::split_paths(&paths).map(|d| d.join(exe)).find(|p| p.exists()))
}
